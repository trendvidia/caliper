package analysis

import (
	"go/ast"
	"go/types"
	"os"
	"path/filepath"
	"testing"

	"golang.org/x/tools/go/packages"
)

func setupTestProject(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module testpkg\n\ngo 1.23\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// --------------------------------------------------------------------------
// Generated code handling
// --------------------------------------------------------------------------

func TestEngine_SkipGeneratedFiles(t *testing.T) {
	dir := setupTestProject(t, map[string]string{
		"generated.go": "// Code generated by tool; DO NOT EDIT.\n\npackage testpkg\n\nfunc Generated() {}\n",
		"normal.go":    "package testpkg\n\nfunc Normal() {}\n",
	})

	// Default: skip generated files.
	engine, err := NewEngine(dir)
	if err != nil {
		t.Fatal(err)
	}

	funcs := engine.FuncNodes()
	for _, fc := range funcs {
		if fc.Func.Name.Name == "Generated" {
			t.Error("generated function should be skipped by default")
		}
	}

	hasNormal := false
	for _, fc := range funcs {
		if fc.Func.Name.Name == "Normal" {
			hasNormal = true
		}
	}
	if !hasNormal {
		t.Error("normal function should not be skipped")
	}
}

func TestEngine_IncludeGeneratedFiles(t *testing.T) {
	dir := setupTestProject(t, map[string]string{
		"generated.go": "// Code generated by tool; DO NOT EDIT.\n\npackage testpkg\n\nfunc Generated() {}\n",
		"normal.go":    "package testpkg\n\nfunc Normal() {}\n",
	})

	opts := DefaultOptions()
	opts.SkipGenerated = false
	engine, err := NewEngineWithOptions(dir, opts)
	if err != nil {
		t.Fatal(err)
	}

	hasGenerated := false
	for _, fc := range engine.FuncNodes() {
		if fc.Func.Name.Name == "Generated" {
			hasGenerated = true
		}
	}
	if !hasGenerated {
		t.Error("generated function should be included when SkipGenerated=false")
	}
}

// --------------------------------------------------------------------------
// Walk also skips generated files
// --------------------------------------------------------------------------

func TestEngine_WalkSkipsGenerated(t *testing.T) {
	dir := setupTestProject(t, map[string]string{
		"generated.go": "// Code generated by tool; DO NOT EDIT.\n\npackage testpkg\n\nfunc Generated() {}\n",
		"normal.go":    "package testpkg\n\nfunc Normal() {}\n",
	})

	engine, err := NewEngine(dir)
	if err != nil {
		t.Fatal(err)
	}

	var funcNames []string
	engine.Walk(func(_ *packages.Package, _ *ast.File, node ast.Node, _ *types.Info) bool {
		if fd, ok := node.(*ast.FuncDecl); ok {
			funcNames = append(funcNames, fd.Name.Name)
		}
		return true
	})

	for _, name := range funcNames {
		if name == "Generated" {
			t.Error("Walk should skip generated files")
		}
	}
}

