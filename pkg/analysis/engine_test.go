func TestEngine_SkipGeneratedFiles(t *testing.T) {
	dir := setupTestProject(t, map[string]string{
		"generated.go": "// Code generated by tool; DO NOT EDIT.\n\npackage testpkg\n\nfunc Generated() {}\n",
		"normal.go":    "package testpkg\n\nfunc Normal() {}\n",
	})

	// Default: skip generated files.
	engine, err := NewEngine(dir)
	if err != nil {
		t.Fatal(err)
	}

	funcs := engine.FuncNodes()
	for _, fc := range funcs {
		if fc.Func.Name.Name == "Generated" {
			t.Error("generated function should be skipped by default")
		}
	}

	hasNormal := false
	for _, fc := range funcs {
		if fc.Func.Name.Name == "Normal" {
			hasNormal = true
		}
	}
	if !hasNormal {
		t.Error("normal function should not be skipped")
	}
}

