func TestIsCgoFile(t *testing.T) {
	// We can't actually import "C" without cgo, but we can test the detection.
	// Create a file with import "C" and parse it to check.
	dir := setupTestProject(t, map[string]string{
		"normal.go": "package testpkg\n\nfunc Normal() {}\n",
	})

	opts := DefaultOptions()
	opts.SkipCgo = true
	engine, err := NewEngineWithOptions(dir, opts)
	if err != nil {
		t.Fatal(err)
	}

	// Normal files should be included.
	if len(engine.FuncNodes()) == 0 {
		t.Error("expected at least one function from normal.go")
	}
}

