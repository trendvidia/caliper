// --------------------------------------------------------------------------
// Workspace detection
// --------------------------------------------------------------------------

func TestIsWorkspace(t *testing.T) {
	dir := t.TempDir()

	// No go.work → not a workspace.
	if IsWorkspace(dir) {
		t.Error("expected false without go.work")
	}

	// Create go.work → is a workspace.
	if err := os.WriteFile(filepath.Join(dir, "go.work"), []byte("go 1.23\n\nuse .\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if !IsWorkspace(dir) {
		t.Error("expected true with go.work")
	}
}

