package analysis

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func setupConsumerProject(t *testing.T, opts EngineOptions, files map[string]string) *Engine {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module consumer\n\ngo 1.23\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	for name, src := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	engine, err := NewEngineWithOptions(dir, opts)
	if err != nil {
		t.Fatalf("NewEngineWithOptions: %v", err)
	}
	return engine
}

var consumerFiles = map[string]string{
	"main.go": `package consumer

func Shipped() int { return helper() }

func helper() int { return 1 }
`,
	"gen.go": `// Code generated by stub. DO NOT EDIT.

package consumer

func Generated() int { return 2 }
`,
	"main_test.go": `package consumer

import "testing"

func TestShipped(t *testing.T) {
	if Shipped() != 1 {
		t.Fatal("bad")
	}
}
`,
}

// TestTestsOption_IncludesTestFiles covers the new Tests option: test files
// are roughly half the Go source in some repositories, and a consumer
// building a picture of a codebase needs a way to ask for them.
func TestTestsOption_IncludesTestFiles(t *testing.T) {
	hasTestFunc := func(e *Engine) bool {
		for _, fc := range e.FuncNodes() {
			if fc.Func.Name != nil && fc.Func.Name.Name == "TestShipped" {
				return true
			}
		}
		return false
	}

	off := setupConsumerProject(t, DefaultOptions(), consumerFiles)
	if hasTestFunc(off) {
		t.Error("Tests defaults to false but a test function was loaded")
	}

	opts := DefaultOptions()
	opts.Tests = true
	on := setupConsumerProject(t, opts, consumerFiles)
	if !hasTestFunc(on) {
		t.Error("Tests=true did not load test files")
	}
}

// TestSkipGenerated_DoesNotReachCallGraph pins the asymmetry documented on
// EngineOptions.SkipGenerated: it filters AST traversal only. A consumer
// walking the call graph sees generated functions regardless, which is why
// IsGeneratedFunc exists.
func TestSkipGenerated_DoesNotReachCallGraph(t *testing.T) {
	engine := setupConsumerProject(t, DefaultOptions(), consumerFiles) // SkipGenerated: true
	for _, fc := range engine.FuncNodes() {
		if fc.Func.Name != nil && fc.Func.Name.Name == "Generated" {
			t.Fatal("SkipGenerated=true still surfaced a generated func via FuncNodes")
		}
	}

	ipc, err := engine.InterProcedural()
	if err != nil {
		t.Fatalf("InterProcedural: %v", err)
	}

	var generatedInGraph *string
	for fn := range ipc.AllFunctions() {
		if fn.Name() == "Generated" {
			n := fn.Name()
			generatedInGraph = &n
			if !ipc.IsGeneratedFunc(fn) {
				t.Error("IsGeneratedFunc returned false for a func in a generated file")
			}
		}
		if fn.Name() == "helper" && ipc.IsGeneratedFunc(fn) {
			t.Error("IsGeneratedFunc returned true for hand-written code")
		}
	}
	if generatedInGraph == nil {
		t.Error("expected the generated func in the call graph despite SkipGenerated=true; " +
			"if this now filters, update the EngineOptions.SkipGenerated doc comment")
	}
}

// TestGeneratedFiles_Identification covers the file-level accessor.
func TestGeneratedFiles_Identification(t *testing.T) {
	engine := setupConsumerProject(t, DefaultOptions(), consumerFiles)
	gen := engine.GeneratedFiles()
	if len(gen) != 1 {
		t.Fatalf("expected exactly 1 generated file, got %d: %v", len(gen), gen)
	}
	for path := range gen {
		if !strings.HasSuffix(path, "gen.go") {
			t.Errorf("unexpected generated file: %s", path)
		}
		if !engine.IsGeneratedFile(path) {
			t.Errorf("IsGeneratedFile disagrees with GeneratedFiles for %s", path)
		}
	}
	for _, fc := range engine.FuncNodes() {
		if engine.IsGeneratedFile(engine.Fset().Position(fc.Func.Pos()).Filename) {
			t.Error("a func from a generated file reached FuncNodes")
		}
	}
}
